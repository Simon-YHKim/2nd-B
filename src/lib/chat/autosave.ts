// 대화 자동 저장 게이트 (Simon 2026-08-18).
//
// ## 무엇을 바꾸는가
//
// 지금 대화는 **휘발성**이다. 저장소에 대화 테이블이 없다 — `chat_history` 는
// 프롬프트 펜스의 라벨이지 테이블이 아니고, 마이그레이션 어디에도 대화 턴을
// 남기는 곳이 없다. 화면을 벗어나면 오간 말은 사라진다.
//
// 그래서 `secondb.tsx` 의 **담기** 칩이 대화를 위키로 보내는 유일한 길이었고,
// 그건 사용자가 매번 눌러야 하는 길이다. 안 누른 대화는 없었던 일이 된다.
// 제품의 목적("소통해서 깊게 파악")이 사용자의 추가 동작에 걸려 있는 셈이다.
//
// 이 게이트는 그 담기를 **자동으로** 돌린다. 즉 기능을 켜는 스위치가 아니라
// **보관 기간을 바꾸는 스위치**다. 사라지던 말이 남는 말이 된다.
//
// ## 왜 기본값이 OFF 인가
//
// `privacy/prefs.ts` 의 규율이 그렇다 — 보관·프로파일링·외부 처리에 해당하는
// 것은 명시적으로 켜기 전까지 OFF. 여기서 기본값을 ON 으로 두면 사용자는
// "사라진다고 생각하고 한 말"이 남는 것을 모른 채 겪게 된다. 깊은 이야기를
// 유도하는 앱에서 그건 가장 하면 안 되는 종류의 놀라움이다.
//
// **되돌릴 길이 먼저 있다는 것도 전제다.** `/wiki` 가 `deleteWikiPage` 를 이미
// 부르고 있어서 담긴 것은 언제든 지울 수 있다. 지우는 길 없이 자동 저장부터
// 켰다면 그건 순서가 틀린 것이다.
//
// ⚠ **2026-09-08 실측 — 그 전제가 지금 배송에서 충족되지 않는다.**
// `deleteWikiPage` 를 부르는 곳은 `src/app/wiki.tsx:292` 하나뿐이고 그것은
// `WikiLegacy` 안이다. 어느 배포도 그 반쪽을 그리지 않는다(`EXPO_PUBLIC_UI=legacy`
// 를 켜는 배포가 0). 배송되는 위키 화면(`dds-wiki-records-screens.tsx`)에는 삭제
// 어포던스가 **0건**이다. 남아 있는 것은 `/settings` 의 `deleteAllWikiPages` —
// **전부 지우기**이고, 자동 저장된 대화 한 건을 되돌리는 길이 아니다.
//
// 위 문단이 스스로 적어 둔 실패 조건("지우는 길 없이 자동 저장부터 켰다면 그건
// 순서가 틀린 것이다")이 **지금 상태 그대로**다. 기본값이 OFF 라 스스로 켠
// 사용자에게만 해당하지만, 이 전제는 `privacy/prefs.ts` 가 **미성년도 스스로 켤
// 수 있다**고 판단한 근거이기도 하다.
//
// `privacy/prefs.ts` 쪽은 **줄 수를 바꾸지 않고** 한 줄만 고쳤다 — DPIA 앵커
// 다섯 개가 그 파일의 줄번호를 인용하고 있어서(dpia-crisis-rail-anchors), 주석
// 하나 때문에 법률 인용을 밀 수 없다. 그래서 자세한 사실은 여기 모아 둔다.
//
// 이 주석은 근거를 다시 쓰지 않는다 — 사실만 적는다. 되살릴지(페이지 단위 삭제를
// 배송 화면에 넣기) 다르게 볼지는 Simon 결정이다.
// 검사: `src/lib/privacy/__tests__/autosave-undo-path.test.ts`
//
// ## 미성년
//
// 미성년도 켤 수 있다(`MINOR_PROMOTABLE_KEYS`). 바깥으로 나가는 것이 없기
// 때문이다 — 자기 말이 자기 위키로 갈 뿐이고 RLS 로 격리돼 있다. 막으면
// 보호되는 것은 없고, 그 사용자의 대화만 영영 페르소나에 기여하지 못한다.
//
// ⚠ 이 함수는 보안 경계가 아니다. 클라이언트 쪽 정직성 게이트이고,
// `recommendationsAllowed` 와 같은 층위다.

/**
 * 이 대화를 위키에 자동으로 담아도 되는가.
 *
 * 성인·미성년 구분 없이 **명시적으로 켠 경우에만** true. 기본값(미설정·null·
 * undefined)은 전부 false 로 떨어진다 — fail-closed 다.
 */
export function chatAutosaveAllowed(chatAutosavePref: boolean | null | undefined): boolean {
  return chatAutosavePref === true;
}
