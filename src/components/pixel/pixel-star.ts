//
// Simon 결정 2026-08-21 (결정 3): 별자리를 원에서 rect 로 옮기되 "그냥 네모"가
// 아니라 "별 모양, 4 방향으로 빛나는" 것. 그래서 이 모듈은 사각형 하나가 아니라
// **십자로 뻗는 광선**을 rect 4장으로 만든다.
//
// 12셀 격자. 중심이 셀 경계(6번째 선) 위에 오므로 모든 좌표가 중심 기준 정수
// 배수가 되고, 좌우·상하가 정확히 대칭이다. 홀수 격자(11셀)를 쓰면 중심이
// 셀 한가운데라 반 셀(0.5u) 오프셋이 생겨 규칙 1을 지킬 수 없다.
//
//     ......██......      ← 광선(세로): 폭 2셀, 길이 12셀
//     ......██......
//     ......██......
//     .....████.....      ← 중간 십자(세로): 4×6셀
//     ....██████....      ← 중간 십자(가로): 6×4셀
//     ██████████████      ← 광선(가로): 길이 12셀, 폭 2셀
//     ██████████████
//     ....██████....
//     .....████.....
//     ......██......
//     ......██......
//     ......██......
//
// 반환 좌표는 **별 중심 기준**이다. 호출부가 `x + cx`, `y + cy` 로 옮겨 쓴다.

export type PixelRect = { x: number; y: number; w: number; h: number };

/**
 * 별 하나를 이루는 rect 4장. `radius` 는 광선 끝까지의 거리(= 격자 6셀).
 *
 * 셀 크기 u 는 소수여도 되지만 **rect 좌표는 항상 정수**다 — 셀 경계를 각각
 * 반올림한 뒤 그 값을 좌우로 미러링하기 때문에, 반올림 오차가 생겨도 대칭은
 * 깨지지 않는다. (w/2 를 반올림하는 방식이면 한쪽으로 1px 밀린다.)
 *
 * 단조 증가를 강제하는 이유: 아주 작은 별(radius 3~4)에서 반올림이 겹치면
 * 중간 십자가 광선보다 얇아져 별 모양이 무너진다. 겹치면 최소 1px 씩 벌린다.
 */
export function pixelStarRects(radius: number): PixelRect[] {
  const u = radius / 6;
  const a = Math.max(1, Math.round(u)); // 광선 반두께 (1셀)
  const b = Math.max(a + 1, Math.round(2 * u)); // 중간 십자 짧은 변 (2셀)
  const c = Math.max(b + 1, Math.round(3 * u)); // 중간 십자 긴 변 (3셀)
  const d = Math.max(c + 1, Math.round(6 * u)); // 광선 끝 (6셀)

  return [
    { x: -a, y: -d, w: 2 * a, h: 2 * d }, // 세로 광선
    { x: -d, y: -a, w: 2 * d, h: 2 * a }, // 가로 광선
    { x: -b, y: -c, w: 2 * b, h: 2 * c }, // 중간 십자 (세로)
    { x: -c, y: -b, w: 2 * c, h: 2 * b }, // 중간 십자 (가로)
  ];
}

/**
 * 별의 실제 화면 반경. `radius` 를 그대로 쓰면 안 되는 이유는 반올림 때문이다 —
 * 밝기 서열(북극성 > 초점 별 > 쉬는 별)을 비교할 때는 그려진 값을 봐야 한다.
 */
export function pixelStarSpan(radius: number): number {
  const rects = pixelStarRects(radius);
  return Math.max(...rects.map((r) => Math.max(r.w, r.h))) / 2;
}
