/** 정본 이름이든 레지스트리가 쓰던 이름이든 받는다. */
export type AnyGlyphName = PixelGlyphName | GlyphAliasName;

/**
 * 이름 하나로 좁힌다.
 *
 * 호출부가 `"chevron_right"`(옛 레지스트리 이름)를 넘기든 `"chevronRight"`
 * (정본 이름)를 넘기든 같은 그림에 닿아야 한다. 그러지 않으면 이주 도중
 * 파일마다 어느 쪽 이름을 쓰는지가 갈려 다시 두 벌이 된다.
 */
export function resolveGlyph(name: AnyGlyphName): PixelGlyphName {
  return (name in GLYPH_ALIAS ? GLYPH_ALIAS[name as GlyphAliasName] : name) as PixelGlyphName;
}

/**
 * 캐논 JSON 이 **이름으로** 지목하는 아이콘을 그림으로 잇는다.
 *
 * 이름은 캐논이 주고 그림은 여기 있으니, 캐논이 아직 안 그린 이름을 부르면
 * 예외가 나는 게 아니라 **아무것도 안 그려진다** — 화면은 멀쩡히 뜨고 아이콘
 * 자리만 빈다. 조용해서 더 위험한 실패라, 눈에 보이는 대체 표시로 떨어뜨린다.
 *
 * ⚠ 대체로 떨어지는 이름이 몇 개인지는 `canon-icon-names.test.ts` 가 세어서
 *   박아둔다. 그 수는 **줄기만 하고 늘지 않는다** — 새 이름을 캐논에 넣으면서
 *   그림을 안 그리면 검사가 깨진다.
 */
export function canonGlyph(name: string): PixelGlyphName {
  if (name in GLYPH_ALIAS) return GLYPH_ALIAS[name as GlyphAliasName];
  if (name in PIXEL_GLYPHS) return name as PixelGlyphName;
  return "sparkle";
}

/**
 * 같은 배열을 SVG 마크업 문자열로. `SvgXml` 에 넘기는 레지스트리가 쓴다 —
 * 두 벌을 만들지 않기 위해서다.
 */
export function glyphMarkup(name: PixelGlyphName, fill: string): string {
  const body = PIXEL_GLYPHS[name]
    .map((g) => `<rect x="${g.x}" y="${g.y}" width="${g.w}" height="${g.h}" fill="${fill}"/>`)
    .join("");
  return `<svg viewBox="0 0 ${GLYPH_BOX} ${GLYPH_BOX}" xmlns="http://www.w3.org/2000/svg" shape-rendering="crispEdges">${body}</svg>`;
}
