/* Generate Metro's literal require map from the approved 144-asset manifest. */
const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const manifestPath = path.join(root, "design/avatar-style-v2/manifest.json");
const outputPath = path.join(root, "src/lib/avatar/thumbnails.ts");
const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
const categories = ["hair", "accessory", "face", "expression", "animal", "job", "garment"];
const records = Object.fromEntries(categories.map((category) => [category, []]));

for (const asset of manifest.assets) {
  if (!Object.hasOwn(records, asset.group) ||
      !/^[a-z0-9]+$/.test(asset.id) ||
      asset.path !== `assets/${asset.group}/${asset.id}.png`) {
    throw new Error("Invalid approved avatar manifest entry");
  }
  const source = path.join(path.dirname(manifestPath), asset.path);
  if (!fs.existsSync(source)) throw new Error(`Missing approved avatar asset: ${asset.path}`);
  records[asset.group].push(
    `    ${asset.id}: require("../../../design/avatar-style-v2/${asset.path}"),`,
  );
}
if (manifest.assets.length !== 144 ||
    categories.some((category) => records[category].length !== manifest.counts[category])) {
  throw new Error("Approved avatar manifest catalog count changed");
}

const lines = [
  "// Generated by scripts/avatar-sync-thumbnails.cjs. Do not edit by hand.",
  'import type { ImageSourcePropType } from "react-native";',
  "",
  `export type AvatarThumbnailCategory = ${categories.map((c) => JSON.stringify(c)).join(" | ")};`,
  "",
  "const thumbnails: Record<AvatarThumbnailCategory, Record<string, ImageSourcePropType>> = {",
  ...categories.flatMap((category) => [
    `  ${category}: {`,
    ...records[category],
    "  },",
  ]),
  "};",
  "",
  "export function getAvatarThumbnail(",
  "  category: AvatarThumbnailCategory,",
  "  id: string,",
  "): ImageSourcePropType | null {",
  "  return thumbnails[category][id] ?? null;",
  "}",
  "",
];
const expected = lines.join("\n");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
  if (current !== expected) throw new Error("Avatar thumbnail map is out of sync");
  process.stdout.write("Approved avatar thumbnail map is in sync (144 assets)\n");
} else {
  fs.writeFileSync(outputPath, expected);
  process.stdout.write("Wrote approved avatar thumbnail map (144 assets)\n");
}
