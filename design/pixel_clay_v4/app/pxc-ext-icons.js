  /* the bundle exposes ICONS + ICON_GRID but not the string renderer — provide one */
  function iconSVG(name, size) {
    var def = DS.ICONS[name]; if (!def) return '';
    var g = DS.ICON_GRID(def), r = '', y, x, w;
    for (y = 0; y < 16; y++) { x = 0;
      while (x < 16) { if (g[y][x]) { w = 0; while (x + w < 16 && g[y][x + w]) w++;
        r += '<rect x="' + x + '" y="' + y + '" width="' + w + '" height="1"/>'; x += w; } else x++; } }
    return '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="' + (size || 16) + '" height="' +
      (size || 16) + '" shape-rendering="crispEdges" role="img" aria-label="' + name + '">' + r + '</svg>';
  }

  /* Clipboard first; if the host blocks it, fall back to a file download.
     Never leaves the user without an export path. */
  function exportSVG(svg, name, done) {
    function fallback() {
      try {
        var url = URL.createObjectURL(new Blob([svg], { type: 'image/svg+xml' }));
        var a = document.createElement('a');
        a.href = url; a.download = name + '.svg';
        document.body.appendChild(a); a.click(); a.remove();
        setTimeout(function () { URL.revokeObjectURL(url); }, 1000);
        done('download');
      } catch (e) { done('fail'); }
    }
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(svg).then(function () { done('copy'); }, fallback);
    } else fallback();
  }

